#!/usr/bin/env python3
"""Build js/stat-weights-data.js from Pawn's ClassicHawsJon.lua.

Source: https://github.com/VgerMods/Pawn/blob/main/ClassicHawsJon.lua
  "WoW Classic Era, Burning Crusade Classic, Wrath Classic, and Forever scales
   curated by HawsJon".  We read the `VgerCore.IsForever` section (the WoW:
  Forever scales), because Forever's Hunter / Priest / Warrior / etc. kits are
  not identical to Classic Era's.  Pawn is (c) Travis Spomer, released under
  CC BY-NC-ND 3.0; the numbers are copied unchanged and credited, never edited.

Usage:  python3 tools/stat-weights/build_stat_weights.py [path/to/ClassicHawsJon.lua]
Every value is multiplied out exactly as the Lua does it (`CritRatingPer*0.8`
etc. use the file's own "Level 60 rating conversions" block), so the output is
"weight per 1 item stat as it shows on a Classic/Forever tooltip, Agility-or-
Strength primary stat = 1".
"""
import json, re, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
LUA = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE / "ClassicHawsJon.lua"
OUT = HERE.parent.parent / "js" / "stat-weights-data.js"
PAWN_COMMIT = "c170b9d18369c4a720bad1ac21c48b0d32ab6873"   # last commit touching the file (2026-11-12)

txt = LUA.read_text()

# "Level 60 rating conversions" for VgerCore.IsClassic or VgerCore.IsForever
conv_block = txt[txt.index("if VgerCore.IsClassic or VgerCore.IsForever then"):]
conv_block = conv_block[:conv_block.index("else")]
PER = {k: float(v) for k, v in re.findall(r"(\w+RatingPer|ArmorPenetrationPer|SpellPenetrationPer)\s*=\s*([\d.]+)", conv_block)}

CLS = {1: "Warrior", 2: "Paladin", 3: "Hunter", 4: "Rogue", 5: "Priest",
       7: "Shaman", 8: "Mage", 9: "Warlock", 11: "Druid"}

i_fo = txt.index("elseif VgerCore.IsForever then")
i_end = txt.index("elseif VgerCore.Is", i_fo + 10)
block = txt[i_fo:i_end]

specs = {}
pat = re.compile(r"PawnAddPluginScaleFromTemplate\(\s*ScaleProviderName,\s*(\d+),\s*--\s*([^\n]*)\n\s*(\d+),\s*--\s*([^\n]*)\n\s*\{(.*?)\}\s*\)", re.S)
for m in pat.finditer(block):
    cls = CLS[int(m.group(1))]
    spec = m.group(4).strip()
    row = {}
    for k, v in re.findall(r"(\w+)=([A-Za-z]+\*[\d.]+|[\d.]+)", m.group(5)):
        if k.startswith("Is") or k == "MetaSocketEffect":
            continue
        if "*" in v:
            a, b = v.split("*")
            val = PER[a] * float(b)
        else:
            val = float(v)
        if val:
            row[k] = round(val, 4)
    specs.setdefault(cls, {})[spec] = row

data = {
    "schema": 1,
    "source": {
        "name": "Pawn \"Classic\" stat-weight scales, WoW Forever section, curated by HawsJon",
        "url": "https://github.com/VgerMods/Pawn/blob/%s/ClassicHawsJon.lua" % PAWN_COMMIT,
        "repo": "https://github.com/VgerMods/Pawn",
        "commit": PAWN_COMMIT,
        "commitDate": "2026-11-12",
        "retrieved": "2026-11-23",
        "section": "VgerCore.IsForever",
        "license": "Pawn is (c) 2006-2026 Travis Spomer, Creative Commons Attribution-NonCommercial-NoDerivs 3.0",
        "units": "weight per 1 point of the stat as it appears on a Classic/Forever item tooltip; the spec's main stat (Agility, Strength, Intellect, Spirit or Stamina) is about 1",
        "ratingPer": PER,
    },
    "specs": specs,
}
OUT.write_text("/* GENERATED by tools/stat-weights/build_stat_weights.py - do not edit by hand. */\n"
               "window.STAT_WEIGHT_DATA = " + json.dumps(data, indent=1, sort_keys=False) + ";\n")
print("wrote", OUT, sum(len(v) for v in specs.values()), "specs in", len(specs), "classes")
