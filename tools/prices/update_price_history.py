#!/usr/bin/env python3
"""Merge the current data/prices.json snapshot into a compact 7-day rolling
history of marketValue, written to data/price-history.json + .js.

The prices-data branch is force-pushed as a single commit, so git history
there is not kept. This file is the history: each run loads the previous
price-history.json (if any), drops samples older than 7 days, appends the
new snapshot, and writes the result back. prices.json itself is unchanged.

Usage:
  python3 tools/prices/update_price_history.py --root . --prev /tmp/price-history.prev.json
  python3 tools/prices/update_price_history.py --root . --import-dir /tmp/price-snaps
"""
from __future__ import annotations

import argparse
import json
import os
import sys
from datetime import datetime, timedelta, timezone
from pathlib import Path

WINDOW_DAYS = 7


def parse_iso(s: str) -> datetime:
    if not s:
        return datetime.now(timezone.utc)
    if s.endswith("Z"):
        s = s[:-1] + "+00:00"
    return datetime.fromisoformat(s)


def load_prices(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def market_value(row) -> int | None:
    if row is None:
        return None
    if isinstance(row, list):
        v = row[1] if len(row) > 1 else None
    else:
        v = row.get("marketValue")
    if v is None:
        return None
    v = int(v)
    return v if v > 0 else None


def merge(prev: dict | None, snapshot: dict, window_days: int = WINDOW_DAYS) -> dict:
    updated = snapshot.get("updated") or snapshot.get("fetched")
    stamp = parse_iso(updated)
    cutoff = stamp - timedelta(days=window_days)

    samples = []
    item_cols: dict[str, list] = {}
    if prev and prev.get("samples") and prev.get("items"):
        for i, s in enumerate(prev["samples"]):
            ts = s.get("updated") if isinstance(s, dict) else s
            try:
                when = parse_iso(ts)
            except ValueError:
                continue
            if when < cutoff:
                continue
            # skip a sample with the same timestamp as the new one (re-run)
            if ts == updated:
                continue
            samples.append({"updated": ts})
            for iid, arr in prev["items"].items():
                val = arr[i] if isinstance(arr, list) and i < len(arr) else None
                item_cols.setdefault(str(iid), []).append(val)
            # items missing in prev row already handled by index; pad those we
            # have already started to the current sample count
            n = len(samples)
            for iid, col in item_cols.items():
                while len(col) < n:
                    col.append(None)

    # Append the new snapshot
    samples.append({"updated": updated})
    priced = snapshot.get("items") or {}
    n = len(samples)
    for iid, row in priced.items():
        col = item_cols.setdefault(str(iid), [None] * (n - 1))
        while len(col) < n - 1:
            col.append(None)
        col.append(market_value(row))
    for iid, col in item_cols.items():
        while len(col) < n:
            col.append(None)

    # Drop items with no values left in the window
    items = {iid: col for iid, col in item_cols.items() if any(v is not None for v in col)}

    return {
        "schema": 1,
        "region": snapshot.get("region") or (prev or {}).get("region") or "US",
        "ruleset": snapshot.get("ruleset") or (prev or {}).get("ruleset") or "Normal",
        "faction": snapshot.get("faction") or (prev or {}).get("faction") or "Horde",
        "house": snapshot.get("house") or (prev or {}).get("house") or 114,
        "houseName": snapshot.get("houseName") or (prev or {}).get("houseName") or "Horde Auction House",
        "windowDays": window_days,
        "units": "copper; each items[id] entry is marketValue at the matching samples[] timestamp, or null if the item was not in that snapshot",
        "source": "Rolling marketValue from the US Normal Horde price snapshots. Kept in this file because the prices-data branch is force-pushed and has no git history.",
        "updated": updated,
        "sampleCount": len(samples),
        "itemCount": len(items),
        "samples": samples,
        "items": items,
    }


def write_history(hist: dict, root: Path) -> None:
    data_dir = root / "data"
    data_dir.mkdir(parents=True, exist_ok=True)
    body = json.dumps(hist, separators=(",", ":"), ensure_ascii=False)
    (data_dir / "price-history.json").write_text(body + "\n", encoding="utf-8")
    (data_dir / "price-history.js").write_text(
        "/* 7-day rolling marketValue history; regenerated by tools/prices/update_price_history.py */\n"
        "window.PRICE_HISTORY = " + body + ";\n",
        encoding="utf-8",
    )
    print(
        "Wrote price history: %d samples, %d items, %d bytes (window %d days, latest %s)"
        % (hist["sampleCount"], hist["itemCount"], len(body), hist["windowDays"], hist["updated"])
    )


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--root", default=".", help="site root (contains data/prices.json)")
    ap.add_argument("--prev", default=None, help="previous price-history.json, if any")
    ap.add_argument("--import-dir", default=None, help="directory of past prices.json snapshots to replay (oldest first by updated)")
    ap.add_argument("--window-days", type=int, default=WINDOW_DAYS)
    args = ap.parse_args()
    root = Path(args.root).resolve()

    if args.import_dir:
        snaps = []
        for p in Path(args.import_dir).glob("*.json"):
            d = load_prices(p)
            if d.get("items") and d.get("updated"):
                snaps.append(d)
        snaps.sort(key=lambda d: d["updated"])
        if not snaps:
            print("No snapshots in", args.import_dir, file=sys.stderr)
            return 1
        hist = None
        for d in snaps:
            hist = merge(hist, d, args.window_days)
        write_history(hist, root)
        return 0

    prices_path = root / "data" / "prices.json"
    if not prices_path.is_file():
        print("missing", prices_path, file=sys.stderr)
        return 1
    snapshot = load_prices(prices_path)
    prev = None
    if args.prev:
        pp = Path(args.prev)
        if pp.is_file() and pp.stat().st_size > 20:
            try:
                prev = load_prices(pp)
            except json.JSONDecodeError as e:
                print("warning: could not read previous history (%s); starting a new window" % e, file=sys.stderr)
    hist = merge(prev, snapshot, args.window_days)
    write_history(hist, root)
    return 0


if __name__ == "__main__":
    sys.exit(main())
